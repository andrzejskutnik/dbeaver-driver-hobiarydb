package pl.hobiarydb.jdbc;

import pl.hobiarydb.jdbc.tcp.HobiaryTcpSocket;

import java.sql.*;

public class HobiaryStatement implements Statement {

    protected final HobiaryConnection conn;
    private boolean closed = false;
    private int maxRows = 0;
    private int queryTimeout = 0;
    private ResultSet lastResultSet = null;
    private int updateCount = -1;

    HobiaryStatement(HobiaryConnection conn) {
        this.conn = conn;
    }

    // ── SQL execution ────────────────────────────────────────────────────────

    @Override
    public ResultSet executeQuery(String sql) throws SQLException {
        conn.checkOpen();
        checkOpen();
        HobiaryTcpSocket.QueryResult result = conn.socket().execute(sql);
        lastResultSet = new HobiaryResultSet(result.columns(), result.rows(), this);
        updateCount = -1;
        return lastResultSet;
    }

    @Override
    public int executeUpdate(String sql) throws SQLException {
        conn.checkOpen();
        checkOpen();
        HobiaryTcpSocket.QueryResult result = conn.socket().execute(sql);
        updateCount = result.affected();
        lastResultSet = null;
        return updateCount;
    }

    @Override
    public boolean execute(String sql) throws SQLException {
        conn.checkOpen();
        checkOpen();
        HobiaryTcpSocket.QueryResult result = conn.socket().execute(sql);
        if (result.hasResultSet()) {
            lastResultSet = new HobiaryResultSet(result.columns(), result.rows(), this);
            updateCount = -1;
            return true;
        } else {
            updateCount = result.affected();
            lastResultSet = null;
            return false;
        }
    }

    private void checkOpen() throws SQLException {
        if (closed)
            throw new SQLException("Statement is closed");
    }

    @Override
    public void close() {
        closed = true;
    }

    @Override
    public boolean isClosed() {
        return closed;
    }

    @Override
    public int getMaxRows() {
        return maxRows;
    }

    @Override
    public void setMaxRows(int max) {
        this.maxRows = max;
    }

    @Override
    public int getQueryTimeout() {
        return queryTimeout;
    }

    @Override
    public void setQueryTimeout(int seconds) {
        this.queryTimeout = seconds;
    }

    @Override
    public Connection getConnection() {
        return conn;
    }

    @Override
    public ResultSet getResultSet() {
        return lastResultSet;
    }

    @Override
    public int getUpdateCount() {
        return updateCount;
    }

    @Override
    public boolean getMoreResults() {
        return false;
    }

    @Override
    public void cancel() {
    }

    @Override
    public SQLWarning getWarnings() {
        return null;
    }

    @Override
    public void clearWarnings() {
    }

    @Override
    public void setCursorName(String name) {
    }

    @Override
    public ResultSet getGeneratedKeys() throws SQLException {
        throw new SQLFeatureNotSupportedException();
    }

    @Override
    public int getMaxFieldSize() {
        return 0;
    }

    @Override
    public void setMaxFieldSize(int max) {
    }

    @Override
    public void setEscapeProcessing(boolean enable) {
    }

    @Override
    public void addBatch(String sql) throws SQLException {
        throw new SQLFeatureNotSupportedException("addBatch");
    }

    @Override
    public void clearBatch() throws SQLException {
        throw new SQLFeatureNotSupportedException("clearBatch");
    }

    @Override
    public int[] executeBatch() throws SQLException {
        throw new SQLFeatureNotSupportedException("executeBatch");
    }

    @Override
    public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public int executeUpdate(String sql, int[] columnIndexes) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public int executeUpdate(String sql, String[] columnNames) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public boolean execute(String sql, int autoGeneratedKeys) throws SQLException {
        return execute(sql);
    }

    @Override
    public boolean execute(String sql, int[] columnIndexes) throws SQLException {
        return execute(sql);
    }

    @Override
    public boolean execute(String sql, String[] columnNames) throws SQLException {
        return execute(sql);
    }

    @Override
    public int getResultSetHoldability() {
        return ResultSet.CLOSE_CURSORS_AT_COMMIT;
    }

    @Override
    public int getResultSetConcurrency() {
        return ResultSet.CONCUR_READ_ONLY;
    }

    @Override
    public int getResultSetType() {
        return ResultSet.TYPE_FORWARD_ONLY;
    }

    @Override
    public int getFetchDirection() {
        return ResultSet.FETCH_FORWARD;
    }

    @Override
    public void setFetchDirection(int direction) {
    }

    @Override
    public int getFetchSize() {
        return 0;
    }

    @Override
    public void setFetchSize(int rows) {
    }

    @Override
    public boolean getMoreResults(int current) {
        return false;
    }

    @Override
    public long getLargeUpdateCount() {
        return updateCount;
    }

    @Override
    public long[] executeLargeBatch() throws SQLException {
        throw new SQLFeatureNotSupportedException();
    }

    @Override
    public long executeLargeUpdate(String sql) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public long executeLargeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public long executeLargeUpdate(String sql, int[] columnIndexes) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public long executeLargeUpdate(String sql, String[] columnNames) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public void setPoolable(boolean poolable) {
    }

    @Override
    public boolean isPoolable() {
        return false;
    }

    @Override
    public void closeOnCompletion() {
    }

    @Override
    public boolean isCloseOnCompletion() {
        return false;
    }

    @Override
    public <T> T unwrap(Class<T> iface) throws SQLException {
        if (iface.isInstance(this))
            return iface.cast(this);
        throw new SQLException("Not a wrapper for " + iface);
    }

    @Override
    public boolean isWrapperFor(Class<?> iface) {
        return iface.isInstance(this);
    }
}
