package pl.hobiarydb.jdbc;

import pl.hobiarydb.jdbc.tcp.HobiaryTcpSocket;

import java.sql.*;
import java.util.Map;
import java.util.Properties;
import java.util.concurrent.Executor;

/**
 * JDBC Connection to a HobiaryDB server via TCP.
 *
 * Each HobiaryConnection owns one HobiaryTcpSocket.
 * Connections are not thread-safe — use one connection per thread
 * or add external synchronization.
 */
public class HobiaryConnection implements Connection {

    private final HobiaryTcpSocket socket;
    private final String           url;
    private boolean autoCommit = true;

    HobiaryConnection(HobiaryTcpSocket socket, String url) {
        this.socket = socket;
        this.url    = url;
    }

    HobiaryTcpSocket socket() {
        return socket;
    }

    String getUrl() {
        return url;
    }

    void checkOpen() throws SQLException {
        if (socket.isClosed())
            throw new SQLException("Connection is closed");
    }

    @Override
    public Statement createStatement() throws SQLException {
        checkOpen();
        return new HobiaryStatement(this);
    }

    @Override
    public PreparedStatement prepareStatement(String sql) throws SQLException {
        checkOpen();
        return new HobiaryPreparedStatement(this, sql);
    }

    @Override
    public void close() throws SQLException {
        try {
            socket.close();
        } catch (java.io.IOException e) {
            throw new SQLException("Error closing connection: " + e.getMessage(), e);
        }
    }

    @Override
    public boolean isClosed() {
        return socket.isClosed();
    }

    @Override
    public DatabaseMetaData getMetaData() throws SQLException {
        checkOpen();
        return new HobiaryDatabaseMetaData(this);
    }

    @Override
    public boolean getAutoCommit() {
        return autoCommit;
    }

    @Override
    public void setAutoCommit(boolean ac) {
        this.autoCommit = ac;
    }

    @Override
    public void commit() throws SQLException {
        checkOpen();
    }

    @Override
    public void rollback() throws SQLException {
        checkOpen();
    }

    @Override
    public Statement createStatement(int resultSetType, int resultSetConcurrency)
            throws SQLException {
        return createStatement();
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int resultSetType,
            int resultSetConcurrency) throws SQLException {
        return prepareStatement(sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys)
            throws SQLException {
        return prepareStatement(sql);
    }

    // ── Not supported ────────────────────────────────────────────────────────

    @Override
    public CallableStatement prepareCall(String sql) throws SQLException {
        throw new SQLFeatureNotSupportedException("prepareCall");
    }

    @Override
    public CallableStatement prepareCall(String sql, int resultSetType,
            int resultSetConcurrency) throws SQLException {
        throw new SQLFeatureNotSupportedException("prepareCall");
    }

    @Override
    public String nativeSQL(String sql) {
        return sql;
    }

    @Override public void setReadOnly(boolean ro)    { }
    @Override public boolean isReadOnly()            { return false; }
    @Override public void setCatalog(String catalog) { }
    @Override public String getCatalog()             { return null; }
    @Override public void setTransactionIsolation(int level) { }
    @Override public int getTransactionIsolation()   { return TRANSACTION_NONE; }
    @Override public SQLWarning getWarnings()        { return null; }
    @Override public void clearWarnings()            { }
    @Override public Map<String, Class<?>> getTypeMap() { return java.util.Collections.emptyMap(); }
    @Override public void setTypeMap(Map<String, Class<?>> map) { }
    @Override public void setHoldability(int h)      { }
    @Override public int getHoldability()            { return ResultSet.CLOSE_CURSORS_AT_COMMIT; }

    @Override
    public Savepoint setSavepoint() throws SQLException {
        throw new SQLFeatureNotSupportedException();
    }

    @Override
    public Savepoint setSavepoint(String name) throws SQLException {
        throw new SQLFeatureNotSupportedException();
    }

    @Override
    public void rollback(Savepoint sp) throws SQLException {
        throw new SQLFeatureNotSupportedException();
    }

    @Override
    public void releaseSavepoint(Savepoint sp) throws SQLException {
        throw new SQLFeatureNotSupportedException();
    }

    @Override
    public Statement createStatement(int a, int b, int c) throws SQLException {
        return createStatement();
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int a, int b, int c)
            throws SQLException {
        return prepareStatement(sql);
    }

    @Override
    public CallableStatement prepareCall(String sql, int a, int b, int c) throws SQLException {
        throw new SQLFeatureNotSupportedException();
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int[] colIdxs) throws SQLException {
        return prepareStatement(sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, String[] colNames) throws SQLException {
        return prepareStatement(sql);
    }

    @Override public Clob createClob()   throws SQLException { throw new SQLFeatureNotSupportedException(); }
    @Override public Blob createBlob()   throws SQLException { throw new SQLFeatureNotSupportedException(); }
    @Override public NClob createNClob() throws SQLException { throw new SQLFeatureNotSupportedException(); }
    @Override public SQLXML createSQLXML() throws SQLException { throw new SQLFeatureNotSupportedException(); }

    @Override
    public boolean isValid(int timeout) {
        return !socket.isClosed();
    }

    @Override public void setClientInfo(String name, String value) { }
    @Override public void setClientInfo(Properties props)          { }
    @Override public String getClientInfo(String name)             { return null; }
    @Override public Properties getClientInfo()                    { return new Properties(); }

    @Override
    public Array createArrayOf(String typeName, Object[] elements) throws SQLException {
        throw new SQLFeatureNotSupportedException();
    }

    @Override
    public Struct createStruct(String typeName, Object[] attributes) throws SQLException {
        throw new SQLFeatureNotSupportedException();
    }

    @Override public void setSchema(String schema)    { }
    @Override public String getSchema()               { return null; }

    @Override
    public void abort(Executor executor) throws SQLException {
        close();
    }

    @Override public void setNetworkTimeout(Executor executor, int ms) { }
    @Override public int getNetworkTimeout()                           { return 0; }

    @Override
    public <T> T unwrap(Class<T> iface) throws SQLException {
        if (iface.isInstance(this))
            return iface.cast(this);
        throw new SQLException("Not a wrapper for " + iface);
    }

    @Override
    public boolean isWrapperFor(Class<?> iface) {
        return iface.isInstance(this);
    }
}
